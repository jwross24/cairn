# Lambda_96
# ----------------------------------------------------------------------------
def primes_of_10_pow_minus_1(n):
    from sympy import cyclotomic_poly, factorint, divisors
    ps = {}
    for d in divisors(n):
        val = int(cyclotomic_poly(d, 10))
        for p, e in factorint(val).items():
            ps[p] = ps.get(p, 0) + e
    # sanity: product reconstructs 10^n - 1
    prod = 1
    for p, e in ps.items():
        prod *= p ** e
    assert prod == 10 ** n - 1
    return ps


def build_lambda(n=LEVEL, verbose=True):
    from sympy import primitive_root
    from sympy.ntheory import discrete_log
    ps = primes_of_10_pow_minus_1(n)
    if verbose:
        print("primes of 10^%d - 1 (with multiplicity):" % n)
        for p in sorted(ps):
            print("   %d^%d" % (p, ps[p]))
    lat = Coset((0, 0), ((1, 0), (0, 1)))
    used = []
    for p in sorted(ps):
        if p in (3, 7):
            continue
        g = int(primitive_root(p))
        l3 = int(discrete_log(p, 3, g))
        l7 = int(discrete_log(p, 7, g))
        assert pow(g, l3, p) == 3 and pow(g, l7, p) == 7
        lat = lat.cut((l3, l7), 0, p - 1)
        used.append(p)
        if verbose:
            print("   p=%d  g=%d  log3=%d log7=%d  index so far %.4e" % (p, g, l3, l7, lat.det()))
    # independent verification: 3^db 7^dc = 1 mod (10^96-1)/(3^e3 * 7^e7)
    N = 10 ** n - 1
    while N % 3 == 0:
        N //= 3
    while N % 7 == 0:
        N //= 7
    for v in lat.B:
        val = 1
        for base, e in ((3, v[0]), (7, v[1])):
            if e >= 0:
                val = val * pow(base, e, N) % N
            else:
                val = val * pow(pow(base, -1, N), -e, N) % N
        assert val == 1, "Lambda basis vector fails the direct congruence"
    return lat, used


