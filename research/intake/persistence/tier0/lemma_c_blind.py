def positive_control(n=50, seed=12345):
    rng = random.Random(seed)
    passed = 0
    details = []
    while len(details) < n:
        a = rng.randint(0, 40)
        b = rng.randint(0, 700)
        c = rng.randint(0, 500)
        y = 2 ** a * 3 ** b * 7 ** c
        nd = len(str(y))
        if nd < 300:
            continue
        coset = Coset((b, c), LAMBDA.B)
        assert coset.contains((b, c))
        ok = True
        c1 = apply_cuts(coset, y % 10 ** LEVEL, a, LEVEL)
        if c1 is None or not c1.contains((b, c)):
            ok = False
        else:
            c2 = apply_cuts(c1, y % 10 ** (2 * LEVEL), a, 2 * LEVEL)
            if c2 is None or not c2.contains((b, c)):
                ok = False
        # also directly from the big coset at K = 192
        c2b = apply_cuts(coset, y % 10 ** (2 * LEVEL), a, 2 * LEVEL)
        if c2b is None or not c2b.contains((b, c)):
            ok = False
        if ok:
            passed += 1
        details.append((a, b, c, nd, ok,
                        math.log10(c1.det()) if c1 else None,
                        math.log10(c2.det()) if ok else None))
    return passed, details


def enumeration_control():
    """A synthetic y' with 6 pattern digits (two in one class) at copies 0/1/2:
    its y' mod 10^{96D} must be among the L values built, D = 1, 2;
    depth-1 count must be 2^6 - 2^4 = 48."""
    digs = [(2, 5), (3, 17), (4, 5), (5, 40), (6, 77), (7, 90)]
    true_t = [0, 1, 2, 0, 1, 2]  # the two class-5 digits at copies 0 and 2
    n = 400
    yp = rep_unit(n)
    for (d, e), t in zip(digs, true_t):
        yp += (d - 1) * 10 ** (e + LEVEL * t)
    ok = True
    cnt1 = 0
    found1 = False
    for assign in itertools.product((0, None), repeat=6):
        L = lower_digits(digs, assign, 1)
        if L is None:
            continue
        cnt1 += 1
        if L == yp % 10 ** LEVEL:
            found1 = True
    found2 = False
    for assign in itertools.product((0, 1, None), repeat=6):
        L = lower_digits(digs, assign, 2)
        if L is None:
            continue
        if L == yp % 10 ** (2 * LEVEL):
            found2 = True
    return cnt1, found1, found2


def negative_control(n=30, seed=99):
    """Corrupt one lower digit of a genuine S-unit: at depth 1 (position 50) and at
    depth 2 (position 150).  Reports how often the true point is excluded / the cut is empty."""
    rng = random.Random(seed)
    out = {"d1_empty": 0, "d1_excluded": 0, "d1_kept": 0, "d2_empty": 0, "d2_excluded": 0, "d2_kept": 0}
    m = 0
    while m < n:
        a = rng.randint(0, 40)
        b = rng.randint(0, 700)
        c = rng.randint(0, 500)
        y = 2 ** a * 3 ** b * 7 ** c
        if len(str(y)) < 300:
            continue
        m += 1
        C = Coset((b, c), LAMBDA.B)
        L1 = y % 10 ** LEVEL
        L1w = L1 + 10 ** 50 if (L1 // 10 ** 50) % 10 != 9 else L1 - 10 ** 50
        c1 = apply_cuts(C, L1w, a, LEVEL)
        if c1 is None:
            out["d1_empty"] += 1
        elif c1.contains((b, c)):
            out["d1_kept"] += 1
        else:
            out["d1_excluded"] += 1
        c1 = apply_cuts(C, L1, a, LEVEL)
        L2 = y % 10 ** (2 * LEVEL)
        L2w = L2 + 10 ** 150 if (L2 // 10 ** 150) % 10 != 9 else L2 - 10 ** 150
        c2 = apply_cuts(c1, L2w, a, 2 * LEVEL)
        if c2 is None:
            out["d2_empty"] += 1
        elif c2.contains((b, c)):
            out["d2_kept"] += 1
        else:
            out["d2_excluded"] += 1
    return out


def image_indices():
    """Index of the image of Lambda_96 in (Z/5^96)^* and (Z/2^96)^* (a = 0), and the
    size of the image of the depth-1 sublattice in the kernel U of G_192 -> G_96."""
    from sympy import factorint
    K = LEVEL
    lam7, K2, t3, t7 = constants(K, 0)
    c5 = LAMBDA.cut((1, lam7), 0, 4 * 5 ** (K - 1))
    img5 = c5.det() // LAMBDA.det()
    c2 = LAMBDA.cut((1, 1), 0, 2).cut((t3, t7), 0, 2 ** (K2 - 2))
    img2 = c2.det() // LAMBDA.det()
    joint = c5.cut((1, 1), 0, 2).cut((t3, t7), 0, 2 ** (K2 - 2))
    imgj = joint.det() // LAMBDA.det()
    # depth-2 refinement of the depth-1 sublattice `joint` (any target: lattice part only)
    lam7b, K2b, t3b, t7b = constants(2 * K, 0)
    d2 = joint.cut((1, lam7b), 0, 4 * 5 ** (2 * K - 1)).cut((1, 1), 0, 2).cut((t3b, t7b), 0, 2 ** (K2b - 2))
    imgU = d2.det() // joint.det()
    return {"img5": img5, "idx5": 4 * 5 ** (K - 1) // img5, "img2": img2, "idx2": 2 ** (K - 1) // img2,
            "idx_joint": 4 * 5 ** (K - 1) * 2 ** (K - 1) // imgj,
            "imgU": imgU, "U": 5 ** K * 2 ** K, "fac_idx5": factorint(4 * 5 ** (K - 1) // img5),
            "fac_idx2": factorint(2 ** (K - 1) // img2)}


def selftest_dlogs():
    from sympy.ntheory import discrete_log
    rng = random.Random(7)
    for K in (8, 12, 20):
        mod = 5 ** K
        for _ in range(5):
            h = rng.randrange(1, mod)
            if h % 5 == 0:
                continue
            x = dlog3_mod5(h, K)
            assert x == int(discrete_log(mod, h, 3)) % (4 * 5 ** (K - 1))
    for K in (5, 9, 20):
        mod = 2 ** K
        for _ in range(5):
            h = rng.randrange(1, mod, 2)
            s, t = dlog_mod2(h, K)
            assert pow(-1, s) * pow(5, t, mod) % mod == h
    # lattice cut self test
    rng = random.Random(3)
    for _ in range(200):
        B = ((rng.randint(-50, 50), rng.randint(-50, 50)), (rng.randint(-50, 50), rng.randint(-50, 50)))
        if det2(B) == 0:
            continue
        v0 = (rng.randint(-100, 100), rng.randint(-100, 100))
        C = Coset(v0, B)
        f = (rng.randint(-30, 30), rng.randint(-30, 30))
        m = rng.randint(1, 40)
        r = rng.randint(0, m - 1)
        C2 = C.cut(f, r, m)
        # brute force check on a box
        for x in range(-40, 41):
            for yv in range(-40, 41):
                inC = C.contains((x, yv))
                sat = (f[0] * x + f[1] * yv - r) % m == 0
                in2 = C2.contains((x, yv)) if C2 else False
                assert in2 == (inC and sat), (B, v0, f, r, m, x, yv)
    return True


