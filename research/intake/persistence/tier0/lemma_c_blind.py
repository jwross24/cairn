def factor_sunit(y):
    a = b = c = 0
    while y % 2 == 0:
        y //= 2
        a += 1
    while y % 3 == 0:
        y //= 3
        b += 1
    while y % 7 == 0:
        y //= 7
        c += 1
    assert y == 1, "anchor is not an S-unit"
    return a, b, c


LAMBDA = None


def process_line(args):
    idx, s, M, a, y = args
    t0 = time.time()
    ay, by, cy = factor_sunit(y)
    note = ""
    if ay != a:
        note = "a(anchor)=%d != a(pattern)=%d" % (ay, a)
    coset = Coset((by, cy), LAMBDA.B)
    reps = representations(M, y)
    out = []
    closed = True
    best = None
    for rep in reps:
        r = lemma_c(rep, a, coset)
        info = {"rep": rep, "cases1": r["cases1"], "n_surv1": len(r["surv1"]),
                "cases2": r["cases2"], "n_surv2": len(r["surv2"])}
        if r["surv2"]:
            closed = False
            info["survivors"] = []
            for assign, c in r["surv2"]:
                lg = c.shortest_log10()
                info["survivors"].append({"assign": assign, "log10_shortest": lg,
                                          "log10_index": math.log10(c.det()) if c.det() < 10 ** 300 else
                                          (c.det().bit_length() * math.log10(2)),
                                          "contains_anchor": c.contains((by, cy))})
                if best is None or lg < best:
                    best = lg
        out.append(info)
    return {"idx": idx, "s": s, "M": M, "a": a, "y": y, "note": note, "nreps": len(reps),
            "closed": closed, "best_log10": best, "reps": out, "time": time.time() - t0}


