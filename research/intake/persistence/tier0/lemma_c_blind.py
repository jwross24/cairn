#!/usr/bin/env python3
"""
Blind re-implementation of Lemma C (the full-depth 10-adic "deep cut"), base 10,
S-units y = 2^a 3^b 7^c, patterns at level 96.

Written from DEEPCUT.md / OPEN-PATTERNS.md only (no access to the original code).

Pieces
  * exact 2-D lattice/coset arithmetic (HNF of generators, Lagrange reduction,
    cutting a coset by a linear congruence f.v = r (mod m));
  * discrete logs in (Z/5^K)^* (base 3, a primitive root) and in
    (Z/2^K)^* = <-1> x <5>, both via p-adic logarithms (exact, O(K) multiplications);
  * Lambda_96 = kernel of (db, dc) -> (db log 3 + dc log 7 mod (p-1))_p over the primes
    p | 10^96 - 1 with p not in {3, 7} (7 DOES divide 10^96-1 since 7 | 10^6-1; it is a
    non-unit for 7^c, so it is dropped, which makes the lattice a superset: conservative);
  * representation enumeration: all (nu, {(d_j, e_j)}) with nu, e_j in [0,96) and
    y + k R_96 = R_nu + sum (d_j-1) 10^{e_j}, 0 <= k <= 9;
  * Lemma C at depths 1 and 2.
"""
import sys, math, random, time, itertools, os
from math import gcd
from collections import Counter
from multiprocessing import Pool

LEVEL = 96


# ----------------------------------------------------------------------------
# integer helpers
# ----------------------------------------------------------------------------
def egcd(a, b):
    """g, x, y with a*x + b*y = g = gcd(a, b) >= 0."""
    x0, y0, x1, y1 = 1, 0, 0, 1
    while b:
        q = a // b
        a, b = b, a - q * b
        x0, x1 = x1, x0 - q * x1
        y0, y1 = y1, y0 - q * y1
    if a < 0:
        a, x0, y0 = -a, -x0, -y0
    return a, x0, y0


def rep_unit(n):
    return (10 ** n - 1) // 9


def v2(n):
    if n == 0:
        return None
    return (n & -n).bit_length() - 1


def crt2(r1, m1, r2, m2):
    """x = r1 mod m1, x = r2 mod m2, gcd(m1, m2) = 1."""
    g, x, y = egcd(m1, m2)
    assert g == 1
    return (r1 * m2 * y + r2 * m1 * x) % (m1 * m2)


# ----------------------------------------------------------------------------
# 2-D lattices and cosets (exact)
# ----------------------------------------------------------------------------
def hnf2(gens):
    """Row-HNF basis ((p, q), (0, r)) of the lattice generated by the 2-vectors gens."""
    piv = None
    rest = []
    for v in gens:
        v = [int(v[0]), int(v[1])]
        if v == [0, 0]:
            continue
        if v[0] == 0:
            rest.append(v)
            continue
        if piv is None:
            piv = v
            continue
        g, x, y = egcd(piv[0], v[0])
        newp = [x * piv[0] + y * v[0], x * piv[1] + y * v[1]]
        other = [0, (v[0] // g) * piv[1] - (piv[0] // g) * v[1]]
        piv = newp
        rest.append(other)
    r = 0
    for v in rest:
        r = gcd(r, v[1])
    if piv is None or r == 0:
        raise ValueError("rank < 2")
    if piv[0] < 0:
        piv = [-piv[0], -piv[1]]
    piv[1] %= r
    return ((piv[0], piv[1]), (0, r))


def dot(u, v):
    return u[0] * v[0] + u[1] * v[1]


def gauss_reduce(b1, b2):
    """Lagrange/Gauss reduction; returns (b1, b2) with b1 a shortest nonzero vector."""
    b1 = tuple(b1)
    b2 = tuple(b2)
    while True:
        n1 = dot(b1, b1)
        n2 = dot(b2, b2)
        if n2 < n1:
            b1, b2 = b2, b1
            n1, n2 = n2, n1
        d = dot(b1, b2)
        mu = (2 * d + n1) // (2 * n1)  # nearest integer to d / n1
        if mu == 0:
            return b1, b2
        b2 = (b2[0] - mu * b1[0], b2[1] - mu * b1[1])


def det2(B):
    return B[0][0] * B[1][1] - B[0][1] * B[1][0]


def kernel_mod(alpha, beta, m):
    """Basis of {u in Z^2 : alpha*u1 + beta*u2 = 0 (mod m)}."""
    alpha %= m
    beta %= m
    g = gcd(gcd(alpha, beta), m)
    a1, b1, m1 = alpha // g, beta // g, m // g
    if m1 == 1:
        return ((1, 0), (0, 1))
    h = gcd(a1, m1)
    mh = m1 // h
    gens = [(m, 0), (0, m), (mh, 0)]
    inv = pow(a1 // h, -1, mh) if mh > 1 else 0
    gens.append(((-b1 * inv) % mh, h))
    B = hnf2(gens)
    for v in B:
        assert (alpha * v[0] + beta * v[1]) % m == 0
    assert abs(det2(B)) == m1, (det2(B), m1)
    return B


class Coset:
    """v0 + L, L = Z b1 + Z b2 (full rank)."""

    __slots__ = ("v0", "B")

    def __init__(self, v0, B, reduce=True):
        self.v0 = (int(v0[0]), int(v0[1]))
        B = (tuple(B[0]), tuple(B[1]))
        if reduce:
            B = gauss_reduce(B[0], B[1])
        self.B = B
        if reduce:
            self.reduce_v0()

    def det(self):
        return abs(det2(self.B))

    def coords(self, w):
        """Rational coordinates of w in basis B: returns (num1, num2, den)."""
        (p, q), (r, s) = self.B
        d = p * s - q * r
        u1 = w[0] * s - w[1] * r
        u2 = p * w[1] - q * w[0]
        return u1, u2, d

    def contains(self, v):
        w = (v[0] - self.v0[0], v[1] - self.v0[1])
        u1, u2, d = self.coords(w)
        return u1 % d == 0 and u2 % d == 0

    def reduce_v0(self):
        u1, u2, d = self.coords(self.v0)
        if d < 0:
            u1, u2, d = -u1, -u2, -d
        k1 = (2 * u1 + d) // (2 * d)
        k2 = (2 * u2 + d) // (2 * d)
        b1, b2 = self.B
        self.v0 = (self.v0[0] - k1 * b1[0] - k2 * b2[0],
                   self.v0[1] - k1 * b1[1] - k2 * b2[1])

    def shortest(self):
        b = self.B[0]
        return math.sqrt(dot(b, b)) if dot(b, b) < 10 ** 600 else None

    def shortest_log10(self):
        b = self.B[0]
        n = dot(b, b)
        return 0.5 * (math.log10(n >> max(0, n.bit_length() - 1000)) +
                      math.log10(2) * max(0, n.bit_length() - 1000))

    def cut(self, f, r, m):
        """Intersect with {v : f.v = r (mod m)}. Returns a Coset or None."""
        b1, b2 = self.B
        alpha = dot(f, b1) % m
        beta = dot(f, b2) % m
        target = (r - dot(f, self.v0)) % m
        g = gcd(gcd(alpha, beta), m)
        if target % g:
            return None
        d, x, y = egcd(alpha, beta)
        if d == 0:
            u = (0, 0)
        else:
            mg = m // g
            k = ((target // g) * pow(d // g, -1, mg)) % mg if mg > 1 else 0
            u = (k * x, k * y)
        nv0 = (self.v0[0] + u[0] * b1[0] + u[1] * b2[0],
               self.v0[1] + u[0] * b1[1] + u[1] * b2[1])
        assert (dot(f, nv0) - r) % m == 0
        K = kernel_mod(alpha, beta, m)
        nB = []
        for k1, k2 in K:
            nB.append((k1 * b1[0] + k2 * b2[0], k1 * b1[1] + k2 * b2[1]))
        c = Coset(nv0, nB)
        # self-check: new basis vectors satisfy the homogeneous congruence
        for v in c.B:
            assert dot(f, v) % m == 0
        return c


# ----------------------------------------------------------------------------
# p-adic logarithms and discrete logs in (Z/5^K)^* and (Z/2^K)^*
# ----------------------------------------------------------------------------
_inv_cache = {}


def padic_log1p(z, p, P):
    """log(1+z) mod p^P for v_p(z) >= 1 (p odd) / >= 2 (p = 2).  Exact."""
    extra = 8
    N = P + 8
    mod = p ** (P + extra)
    key = (p, P)
    if key not in _inv_cache:
        tab = []
        for n in range(1, N + 1):
            v = 0
            nn = n
            while nn % p == 0:
                nn //= p
                v += 1
            tab.append((p ** v, pow(nn, -1, mod)))
        _inv_cache[key] = tab
    tab = _inv_cache[key]
    z %= mod
    total = 0
    zn = 1
    for n in range(1, N + 1):
        zn = zn * z % mod
        pv, inv = tab[n - 1]
        term = (zn // pv) * inv % mod
        if n & 1:
            total += term
        else:
            total -= term
    return total % (p ** P)


_log81 = {}
_log5 = {}


def dlog3_mod5(h, K):
    """x mod 4*5^(K-1) with 3^x = h (mod 5^K)."""
    mod = 5 ** K
    h %= mod
    assert h % 5 != 0
    x4 = {1: 0, 3: 1, 4: 2, 2: 3}[h % 5]
    if K not in _log81:
        lg = padic_log1p(80, 5, K)
        assert lg % 5 == 0 and (lg // 5) % 5 != 0
        _log81[K] = pow(lg // 5, -1, 5 ** (K - 1))
    lh = padic_log1p(pow(h, 4, mod) - 1, 5, K)
    assert lh % 5 == 0
    x5 = (lh // 5) * _log81[K] % (5 ** (K - 1))
    x = crt2(x4, 4, x5, 5 ** (K - 1))
    assert pow(3, x, mod) == h, "dlog3_mod5 failed"
    return x


def dlog_mod2(h, K):
    """(s, t) with h = (-1)^s 5^t (mod 2^K), t mod 2^(K-2); K >= 3."""
    mod = 2 ** K
    h %= mod
    assert h & 1
    s = 0 if h % 4 == 1 else 1
    u = h if s == 0 else (-h) % mod
    if K not in _log5:
        l5 = padic_log1p(4, 2, K)
        assert l5 % 4 == 0 and (l5 // 4) % 2 == 1
        _log5[K] = pow(l5 // 4, -1, 2 ** (K - 2))
    lu = padic_log1p(u - 1, 2, K)
    assert lu % 4 == 0
    t = (lu // 4) * _log5[K] % (2 ** (K - 2))
    assert pow(5, t, mod) == u, "dlog_mod2 failed"
    return s, t


# ----------------------------------------------------------------------------
# the three congruences of Lemma C for a given lower-digit value L at K = 96 D
# ----------------------------------------------------------------------------
_const = {}


def constants(K, a):
    key = (K, a)
    if key not in _const:
        lam7 = dlog3_mod5(7, K)
        K2 = K - a
        s3, t3 = dlog_mod2(3, K2)
        s7, t7 = dlog_mod2(7, K2)
        assert s3 == 1 and s7 == 1
        _const[key] = (lam7, K2, t3, t7)
    return _const[key]


def apply_cuts(coset, L, a, K):
    """Cut coset by:  v2(L) = a,  3^b 7^c = L/2^a (mod 5^K) and (mod 2^(K-a))."""
    if v2(L) != a:
        return None
    T = L >> a
    lam7, K2, t3, t7 = constants(K, a)
    # mod 5^K: b + c*lam7 = log_3(T)  (mod 4*5^(K-1))
    x = dlog3_mod5(T % (5 ** K), K)
    c = coset.cut((1, lam7), x, 4 * 5 ** (K - 1))
    if c is None:
        return None
    # mod 2^(K-a): 3^b 7^c = (-1)^(b+c) 5^(b t3 + c t7) = (-1)^s 5^t
    s, t = dlog_mod2(T % (2 ** K2), K2)
    c = c.cut((1, 1), s, 2)
    if c is None:
        return None
    c = c.cut((t3, t7), t, 2 ** (K2 - 2))
    return c


