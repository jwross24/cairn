# representations of an anchor
# ----------------------------------------------------------------------------
def submultisets(counts):
    digits = sorted(counts)
    for combo in itertools.product(*[range(counts[d] + 1) for d in digits]):
        yield tuple((d, c) for d, c in zip(digits, combo) if c)


def placements(counts, T):
    """All multisets {(d, e)} using exactly the digits in counts with
    sum (d-1) 10^e = T, e in [0, 96)."""
    results = []
    total = sum(counts.values())

    def rec(e, V, counts, used, chosen):
        if V == 0:
            if used == total:
                results.append(tuple(sorted(chosen)))
            return
        if e >= LEVEL or used == total:
            return
        r = V % 10
        for sub in submultisets(counts):
            s = sum((d - 1) * c for d, c in sub)
            if s % 10 != r or s > V:
                continue
            nc = Counter(counts)
            add = []
            for d, c in sub:
                nc[d] -= c
                add += [(d, e)] * c
            rec(e + 1, (V - s) // 10, nc, used + len(add), chosen + add)

    rec(0, T, Counter(counts), 0, [])
    return results


def representations(M, y):
    counts = Counter(int(ch) for ch in M)
    R96 = rep_unit(LEVEL)
    reps = set()
    for k in range(10):
        base = y + k * R96
        for nu in range(LEVEL):
            T = base - rep_unit(nu)
            if T <= 0:
                continue
            for sol in placements(counts, T):
                reps.add((nu, sol))
    # verify each
    for nu, sol in reps:
        val = rep_unit(nu) + sum((d - 1) * 10 ** e for d, e in sol)
        assert (val - y) % R96 == 0 and 0 <= (val - y) // R96 <= 9
        assert sorted(d for d, e in sol) == sorted(int(ch) for ch in M)
    return sorted(reps)


