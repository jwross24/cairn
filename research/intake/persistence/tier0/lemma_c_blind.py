# Lemma C on one representation
# ----------------------------------------------------------------------------
def lower_digits(digs, assign, D):
    """L = R_{96D} + sum_{t_j < D} (d_j-1) 10^{e_j + 96 t_j}; None if positions collide."""
    pos = []
    L = rep_unit(LEVEL * D)
    for (d, e), t in zip(digs, assign):
        if t is None:
            continue
        P = e + LEVEL * t
        pos.append(P)
        L += (d - 1) * 10 ** P
    if len(set(pos)) != len(pos):
        return None
    return L


def lemma_c(rep, a, coset):
    """Returns dict with depth-1 / depth-2 survivors."""
    nu, digs = rep
    q = len(digs)
    # Cases are enumerated per digit; identical digits swapped between copies give the
    # same lower-digit value L, so cases are de-duplicated by L (distinct L = distinct case).
    surv1 = []
    seen1 = set()
    for assign in itertools.product((0, None), repeat=q):
        L = lower_digits(digs, assign, 1)
        if L is None or L in seen1:
            continue
        seen1.add(L)
        c = apply_cuts(coset, L, a, LEVEL)
        if c is not None:
            surv1.append((assign, c))
    surv2 = []
    seen2 = set()
    for assign, c in surv1:
        free = [j for j in range(q) if assign[j] is None]
        for choice in itertools.product((1, None), repeat=len(free)):
            assign2 = list(assign)
            for j, t in zip(free, choice):
                assign2[j] = t
            L = lower_digits(digs, assign2, 2)
            if L is None or L in seen2:
                continue
            seen2.add(L)
            c2 = apply_cuts(c, L, a, 2 * LEVEL)
            if c2 is not None:
                surv2.append((tuple(assign2), c2))
    return {"cases1": len(seen1), "surv1": surv1, "cases2": len(seen2), "surv2": surv2}


