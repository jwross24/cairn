#!/usr/bin/env python3
"""
witness.py — X20: why the prime cuts never kill a wrap-0 shadow, and what does.

For a wrap-0 representation V = y, the anchor's own exponent vector (b_y, c_y) satisfies every modular condition
(2^a 3^b 7^c ≡ y mod p for all p), so the modular coset at every level L is (b_y, c_y) + Λ_L and is never empty.
The shadow's 10-adic class at depth K (window: ones up to K, fixed digits at copy 0, unplaced digits beyond K)
is v_w(K) + Λ_w(K), Λ_w(K) = {λ ∈ Λ_96 : 3^λ_b 7^λ_c ≡ 1 (mod 10^K)}.  The shadow survives level L (K = L) iff
the two classes meet:   δ := v_w(L) − (b_y, c_y) ∈ Λ_L + Λ_w(L).
This script computes that test for L = 192, 384, 768 per word of every wrap-0 representation of the given patterns
and prints it next to the pipeline verdict, plus the 2- and 5-adic index data that govern it.

Usage: python3 witness.py <keys.txt> <trees.jsonl>
"""
import sys, time, math
from collections import Counter
from lattice import Coset
from descent import cut_coset, v2
import deepcut as DC, deepcut_lift as DL, classify_open as C, wordlift as W

P768 = [257, 15361, 434689, 453377, 859393, 33649448872371457]

def lattice_sum(vs):
    """basis of the lattice generated by 2-vectors vs (HNF by gcd elimination)."""
    rows = [list(v) for v in vs if v != (0, 0)]
    # eliminate first coordinate
    while sum(1 for r in rows if r[0] != 0) > 1:
        rows.sort(key=lambda r: (r[0] == 0, abs(r[0])))
        piv = rows[0]
        for r in rows[1:]:
            if r[0] != 0:
                q = r[0] // piv[0]; r[0] -= q * piv[0]; r[1] -= q * piv[1]
    u1 = next((r for r in rows if r[0] != 0), None)
    rest = [r[1] for r in rows if r[0] == 0 and r[1] != 0]
    g = 0
    for x in rest: g = math.gcd(g, x)
    if u1 is None or g == 0: return None
    return (tuple(u1), (0, g))

def kernel_at(Lam, pds):
    co = Coset((0, 0), Lam.u1, Lam.u2)
    for pd in pds:
        co = co.intersect(pd.l3, pd.l7, 0, pd.p - 1)
        assert co is not None
    return co

def two_five_parts(co):
    d = co.index()
    return (v2(d), max(i for i in range(0, 400) if d % 5 ** i == 0))

if __name__ == "__main__":
    keyf, jf = sys.argv[1], sys.argv[2]
    want = set(tuple(l.split()[:4]) for l in open(keyf) if l.strip()); t0 = time.time()
    LEVELS = tuple(int(x) for x in (sys.argv[sys.argv.index('--levels') + 1] if '--levels' in sys.argv else '192,384,768').split(','))
    Lam96 = DC.kernel_lattice(); Lam = {96: Lam96}
    for L in LEVELS:
        ps = P768 if L == 768 else DL.new_primes(L, 96)
        Lam[L] = kernel_at(Lam96, [DL.PD(p) for p in ps])
    for L in (96,) + LEVELS:
        print(f"Λ_{L}: index 10^{math.log10(Lam[L].index()):.1f}, (v2, v5) of index {two_five_parts(Lam[L])}", flush=True)
    Lw = {}
    for K in (96,) + LEVELS:
        Lw[K] = cut_coset(Coset((0, 0), Lam96.u1, Lam96.u2), 0, 1, K)
        print(f"Λ_w({K}) inside Λ_96: index 10^{math.log10(Lw[K].index()):.1f}", flush=True)
    KL = {}
    for L in LEVELS:
        KL[L] = cut_coset(Coset((0, 0), (1, 0), (0, 1)), 0, 1, L)
        S = lattice_sum([Lam[L].u1, Lam[L].u2, KL[L].u1, KL[L].u2]); Sco = Coset((0, 0), *S)
        print(f"[Z² : Λ_{L} + K_{L}] = {Sco.index()} = 2^{v2(Sco.index())} · {Sco.index() >> v2(Sco.index())}   "
              f"(number of 2,5-adic classes the shadow must hit at level {L}) [{time.time()-t0:.0f}s]", flush=True)
    seen = set()
    for (s, M, a, nu, eps, y, sol) in C.entries(jf):
        key = (str(s), ''.join(map(str, M)), str(a), str(y))
        if key not in want or key in seen: continue
        seen.add(key)
        fct = C.factor237(y); by, cy = fct[1], fct[2]
        co0 = Coset((by, cy), Lam96.u1, Lam96.u2)
        reps = DC.all_representations(M, y)
        if nu is not None:
            reps = [r for r in reps if r[0] == nu and Counter(e for _, e in r[1]) == Counter(e % 96 for e in eps)]
        out = []
        for (nu0, De) in reps:
            V = W.R(nu0) + sum((d - 1) * 10 ** e for d, e in De); w = (V - y) // W.R(96)
            if w: out.append(f"w={w}:skip"); continue
            words = W.depth1_words(co0, a, (nu0, De))
            for co, state in words:
                fixed = [(De[j][0], st[1]) for j, st in enumerate(state) if st[0] == 'F']
                res = []
                for L in LEVELS:
                    WK = W.R(L) + sum((d - 1) * 10 ** e for d, e in fixed)
                    cw = cut_coset(Coset((0, 0), (1, 0), (0, 1)), a, WK, L)   # 10-adic class of (b,c) at depth L
                    assert cw is not None
                    S = lattice_sum([Lam[L].u1, Lam[L].u2, cw.u1, cw.u2]); Sco = Coset((0, 0), *S)   # Λ_L + K_L
                    delta = (cw.v0[0] - by, cw.v0[1] - cy)
                    # δ is defined modulo K_L (choice of cw.v0) — fine since K_L ⊆ S
                    res.append('A' if Sco.contains(*delta) else 'x')
                out.append(f"ν={nu0},r={len(De)-len(fixed)}:{''.join(res)}")
        print(f"{' '.join(key)} k={len(M)}: {out} [{time.time()-t0:.0f}s]", flush=True)
