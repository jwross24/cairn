def level_primes(L):
    ps = set()
    for d in divisors(L): ps |= set(int(p) for p in factorint(int(cyclotomic_poly(d, 10))))
    return sorted(p for p in ps if p not in (2, 3, 5, 7))

class PD:
    def __init__(self, p):
        self.p = p; self.g = primitive_root(p)
        self.l2 = discrete_log(p, 2 % p, self.g); self.l3 = discrete_log(p, 3 % p, self.g); self.l7 = discrete_log(p, 7 % p, self.g)

P12 = level_primes(12); P24 = [p for p in level_primes(24) if p not in P12]
PD12 = [PD(p) for p in P12]; PD24 = [PD(p) for p in P24]

def kernel12():
    co = Coset((0, 0), (1, 0), (0, 1))
    for pd in PD12: co = co.intersect(pd.l3, pd.l7, 0, pd.p - 1)
    return co
LAM12 = kernel12()

def coset12(V, a):
    """C_a = {(b,c): 2^a 3^b 7^c ≡ V mod Q_12}, or None."""
    co = Coset((0, 0), (1, 0), (0, 1))                      # start from Z²: the congruences fix the coset of Λ_12
    for pd in PD12:
        r = V % pd.p
        if r == 0: return None
        co = co.intersect(pd.l3, pd.l7, (discrete_log(pd.p, r, pd.g) - a * pd.l2) % (pd.p - 1), pd.p - 1)
        if co is None: return None
    return co

def image_subgroup(co, p):
    """elements of the image of the lattice of `co` in (Z/p)^* (as a set), generated by the basis images."""
    g1 = pow(3, co.u1[0], p) * pow(7, co.u1[1], p) % p; g2 = pow(3, co.u2[0], p) * pow(7, co.u2[1], p) % p
    H = {1}; frontier = [1]
    while frontier:
        x = frontier.pop()
        for g in (g1, g2):
            y = x * g % p
            if y not in H: H.add(y); frontier.append(y)
    return H

def child_passes(co, a, Vp, pds):
    """exact test: does the coset co (at level 12) meet 3^b 7^c ≡ Vp/2^a at every p in pds?"""
    for pd in pds:
        r = Vp % pd.p
        if r == 0: return False
        co = co.intersect(pd.l3, pd.l7, (discrete_log(pd.p, r, pd.g) - a * pd.l2) % (pd.p - 1), pd.p - 1)
        if co is None: return False
    return True

def additive_lift(nu, De, a, co, verify_p=99990001):
    """returns the list of (S-bitmask, sn) children passing all three new primes, found by DP + one modexp each."""
    V = (10 ** nu - 1) // 9 + sum((d - 1) * 10 ** e for d, e in De)
    q = len(De)
    small = [p for p in P24 if p != verify_p]; M = 1
    for p in small: M *= p
    # allowed residues of Δ modulo each small prime, then CRT-combined allowed set mod M
    allowed = {}
    for p in small:
        H = image_subgroup(co, p)
        x = pow(3, co.v0[0], p) * pow(7, co.v0[1], p) % p                 # the coset's image class is x·H
        w = (10 ** 12 - 1) % p; winv = pow(w, -1, p)
        # child passes p  ⟺  (V + w·Δ)/2^a ∈ x·H  ⟺  Δ ≡ (2^a·x·h − V)/w for some h ∈ H   (valid also when V ≡ 0 mod p)
        allowed[p] = {(pow(2, a, p) * x * h - V) * winv % p for h in H}
    # CRT: allowed set mod M
    A = set()
    ps = small
    for combo in itertools.product(*[sorted(allowed[p]) for p in ps]):
        x = 0
        for p, r in zip(ps, combo):
            Mi = M // p; x = (x + r * Mi * pow(Mi, -1, p)) % M
        A.add(x)
    terms = [(d - 1) * pow(10, e, M) % M for d, e in De]
    extra = pow(10, nu, M) * pow(9, -1, M) % M
    # DP over Z/M with mask lists (q ≤ ~20); for larger q use counting DP + backtracking
    reach = {0: [0]}
    for i, t in enumerate(terms):
        new = {}
        for r, masks in reach.items():
            new.setdefault(r, []).extend(masks)
            r2 = (r + t) % M; new.setdefault(r2, []).extend(m | (1 << i) for m in masks)
        reach = new
    cands = []
    for sn in (0, 1):
        for r in A:
            key = (r - sn * extra) % M
            for m in reach.get(key, []): cands.append((m, sn))
    # exact test of each candidate: sequential coset intersection at the three new primes (the per-prime conditions
    # are only NECESSARY — the primes are correlated through the coset — so the DP is a prefilter, never the verdict)
    out = []
    for m, sn in cands:
        nu1 = nu + 12 * sn
        Vp = (10 ** nu1 - 1) // 9 + sum((d - 1) * 10 ** (e + (12 if m >> i & 1 else 0)) for i, (d, e) in enumerate(De))
        if child_passes(co, a, Vp, PD24): out.append((m, sn))
    return out, len(cands), len(A)

def brute_children(nu, De, a, co):
    q = len(De); out = []
    for sn in (0, 1):
        for m in range(1 << q):
            nu1 = nu + 12 * sn
            Vp = (10 ** nu1 - 1) // 9 + sum((d - 1) * 10 ** (e + (12 if m >> i & 1 else 0)) for i, (d, e) in enumerate(De))
            if child_passes(co, a, Vp, PD24): out.append((m, sn))
    return out

