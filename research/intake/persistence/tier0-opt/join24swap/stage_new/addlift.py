"""
addlift.py — the ADDITIVE lift 12 → 24: test all 2^(q+1) level-24 children of a level-12 survivor without
materializing them (LIFT-ADDITIVE.md).

Setting.  A level-12 survivor is (ν, {(d_j, e_j)}, e_j ∈ [0,12), a_0 = a mod 12) with value V = R_ν + Σ (d_j−1)10^{e_j}
and, for each admissible a ≡ a_0 (mod 12), the exponent coset C_a = {(b, c) : 2^a 3^b 7^c ≡ V (mod Q_12)} = v_a + Λ_12.
A level-24 child shifts ν by 12·sn and each digit by 12·t_j: V' = V + (10^12 − 1)·Δ, Δ(S, sn) = Σ_{j∈S}(d_j−1)10^{e_j}
+ sn·10^ν/9 (S = digits with t_j = 1).  The child survives the new primes p ∈ {73, 137, 99990001} of level 24 for
exponent a iff V'/2^a lies in the image of C_a in (Z/p)^*, i.e. iff 1 + u_p·Δ ∈ H_{a,p} := image of Λ_12 (a subgroup
of order |H| = (p−1)/index: 2, 17, 22220), u_p = (10^12 − 1)/V mod p.  So the allowed residues A_{a,p} = {(h−1)/u_p :
h ∈ H_{a,p}} form a set of size |H|, and survival at 73 and 137 is a condition on Δ mod 10001 with 34 allowed residues
(per a).  A subset-sum DP over Z/10001 lists exactly the children passing 73 and 137 (fraction ≈ 1/294); each is then
tested at 99990001 by one modular exponentiation; the survivors (≈ 1/4500 of those) get their level-24 coset by the
usual discrete logs.  Cost per survivor: 10001·(q+1) + 2^(q+1)/294 modexps, against 2^(q+1) residue tests.

Validation (`--selftest`): on real patterns (level-96 anchored records reduced mod 12), brute force all 2^(q+1)
children with child_coset at the three primes and compare with the DP's list — must be identical.
"""
